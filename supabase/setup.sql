begin;

-- ---------------------------------------------------------
-- 1. テーブル
-- ---------------------------------------------------------

-- 管理者（Googleログインのメールアドレス）
create table if not exists public.members (
    email text primary key,
    role text not null default 'admin' check (role in ('admin', 'member')),
    created_at timestamptz not null default now()
);

-- 用途別マップ
create table if not exists public.maps (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null default '',
    is_locked boolean not null default true,
    created_at timestamptz not null default now()
);

-- スポット
create table if not exists public.spots (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    map_id bigint references public.maps(id) on delete cascade,
    name text,
    lat double precision not null,
    lng double precision not null,
    category text,
    subcategory text,
    description text,
    activity_history text,
    note text,
    address text,
    image_url text
);

create index if not exists spots_map_id_idx on public.spots(map_id);

-- スポットの写真
create table if not exists public.spot_images (
    id bigint generated by default as identity primary key,
    spot_id bigint not null references public.spots(id) on delete cascade,
    image_url text,
    file_path text,
    created_at timestamptz not null default now()
);

create index if not exists spot_images_spot_id_idx on public.spot_images(spot_id);

-- 写真の保存場所（公開バケット）
insert into storage.buckets (id, name, public)
values ('spot-images', 'spot-images', true)
on conflict (id) do nothing;

-- ---------------------------------------------------------
-- 2. 判定用の関数
-- ---------------------------------------------------------

create or replace function public.is_map_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.members
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role = 'admin'
    );
$$;

create or replace function public.is_map_unlocked(target_map_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.maps
        where id = target_map_id
          and not is_locked
    );
$$;

create or replace function public.is_spot_editable(target_spot_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.spots s
        join public.maps m on m.id = s.map_id
        where s.id = target_spot_id
          and not m.is_locked
    );
$$;

create or replace function public.is_spot_folder_editable(folder text)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select case
        when folder ~ '^[0-9]+$' then public.is_spot_editable(folder::bigint)
        else false
    end;
$$;

grant execute on function public.is_map_admin() to anon, authenticated;
grant execute on function public.is_map_unlocked(bigint) to anon, authenticated;
grant execute on function public.is_spot_editable(bigint) to anon, authenticated;
grant execute on function public.is_spot_folder_editable(text) to anon, authenticated;

-- テーブルへのアクセス権（実際に何ができるかは、下のRLSルールで絞る）
grant usage on schema public to anon, authenticated;
grant select on public.maps, public.spots, public.spot_images to anon, authenticated;
grant insert, update on public.spots to anon, authenticated;
grant insert, delete on public.spot_images to anon, authenticated;
grant insert, update, delete on public.maps to authenticated;
grant delete on public.spots to authenticated;
grant select on public.members to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------------------------------------------------------
-- 3. ルール（RLS）
-- ---------------------------------------------------------
alter table public.members enable row level security;
alter table public.maps enable row level security;
alter table public.spots enable row level security;
alter table public.spot_images enable row level security;

-- 何度実行しても大丈夫なように、いったん外してから作り直す
do $$
declare
    p record;
begin
    for p in
        select policyname, tablename
        from pg_policies
        where schemaname = 'public'
          and tablename in ('members', 'maps', 'spots', 'spot_images')
    loop
        execute format('drop policy %I on public.%I', p.policyname, p.tablename);
    end loop;

    for p in
        select policyname
        from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and (coalesce(qual, '') || coalesce(with_check, '')) like '%spot-images%'
    loop
        execute format('drop policy %I on storage.objects', p.policyname);
    end loop;
end $$;

-- members：管理者だけが見られる（メールアドレスを公開しない）
create policy "members: 管理者が閲覧"
    on public.members for select
    to authenticated
    using (public.is_map_admin());

-- maps：誰でも見られる／作成・変更・削除は管理者だけ
create policy "maps: 誰でも閲覧"
    on public.maps for select
    to anon, authenticated
    using (true);

create policy "maps: 管理者が作成"
    on public.maps for insert
    to authenticated
    with check (public.is_map_admin());

create policy "maps: 管理者が変更"
    on public.maps for update
    to authenticated
    using (public.is_map_admin())
    with check (public.is_map_admin());

create policy "maps: 管理者が削除"
    on public.maps for delete
    to authenticated
    using (public.is_map_admin());

-- spots：誰でも見られる／ロック解除中なら誰でも追加・編集／削除は管理者だけ
create policy "spots: 誰でも閲覧"
    on public.spots for select
    to anon, authenticated
    using (true);

create policy "spots: ロック解除中なら追加"
    on public.spots for insert
    to anon, authenticated
    with check (public.is_map_unlocked(map_id) or public.is_map_admin());

create policy "spots: ロック解除中なら編集"
    on public.spots for update
    to anon, authenticated
    using (public.is_map_unlocked(map_id) or public.is_map_admin())
    with check (public.is_map_unlocked(map_id) or public.is_map_admin());

create policy "spots: 管理者が削除"
    on public.spots for delete
    to authenticated
    using (public.is_map_admin());

-- spot_images：誰でも見られる／ロック解除中なら誰でも追加・削除
create policy "spot_images: 誰でも閲覧"
    on public.spot_images for select
    to anon, authenticated
    using (true);

create policy "spot_images: ロック解除中なら追加"
    on public.spot_images for insert
    to anon, authenticated
    with check (public.is_spot_editable(spot_id) or public.is_map_admin());

create policy "spot_images: ロック解除中なら削除"
    on public.spot_images for delete
    to anon, authenticated
    using (public.is_spot_editable(spot_id) or public.is_map_admin());

-- Storage（spot-images）：写真ファイルも同じルール
create policy "spot-images: 誰でも閲覧"
    on storage.objects for select
    to anon, authenticated
    using (bucket_id = 'spot-images');

create policy "spot-images: ロック解除中なら追加"
    on storage.objects for insert
    to anon, authenticated
    with check (
        bucket_id = 'spot-images'
        and (
            public.is_spot_folder_editable((storage.foldername(name))[1])
            or public.is_map_admin()
        )
    );

create policy "spot-images: ロック解除中なら削除"
    on storage.objects for delete
    to anon, authenticated
    using (
        bucket_id = 'spot-images'
        and (
            public.is_spot_folder_editable((storage.foldername(name))[1])
            or public.is_map_admin()
        )
    );

