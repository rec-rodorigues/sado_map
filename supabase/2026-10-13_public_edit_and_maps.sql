-- =========================================================
-- 佐渡島マップ：誰でも編集 ＋ マップごとのロック ＋ 用途別マップ
--
-- Supabase ダッシュボード → SQL Editor に全文を貼り付けて「Run」してください。
-- 何度実行しても同じ結果になるように書いています。
-- =========================================================

begin;

-- ---------------------------------------------------------
-- 1. 用途別マップのテーブル
-- ---------------------------------------------------------
create table if not exists public.maps (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null default '',
    is_locked boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.spots
    add column if not exists map_id bigint
    references public.maps(id) on delete cascade;

create index if not exists spots_map_id_idx on public.spots(map_id);

-- 既存のスポットを最初のマップにまとめる（最初はロック状態）
do $$
declare
    default_map_id bigint;
begin
    if not exists (select 1 from public.maps) then
        insert into public.maps (name, description, is_locked)
        values ('佐渡島マップ', 'これまでに登録したスポット', true)
        returning id into default_map_id;

        update public.spots
        set map_id = default_map_id
        where map_id is null;
    end if;
end $$;

-- ---------------------------------------------------------
-- 2. 判定用の関数
-- ---------------------------------------------------------

-- ログイン中のユーザーが管理者か
create or replace function public.is_map_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.members
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role = 'admin'
    );
$$;

-- マップのロックが解除されているか
create or replace function public.is_map_unlocked(target_map_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.maps
        where id = target_map_id
          and not is_locked
    );
$$;

-- スポットが「ロック解除中のマップ」に属しているか
create or replace function public.is_spot_editable(target_spot_id bigint)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.spots s
        join public.maps m on m.id = s.map_id
        where s.id = target_spot_id
          and not m.is_locked
    );
$$;

-- Storageのフォルダ名（= スポットID）から判定
create or replace function public.is_spot_folder_editable(folder text)
returns boolean
language sql stable security definer
set search_path = public
as $$
    select case
        when folder ~ '^[0-9]+$' then public.is_spot_editable(folder::bigint)
        else false
    end;
$$;

grant execute on function public.is_map_admin() to anon, authenticated;
grant execute on function public.is_map_unlocked(bigint) to anon, authenticated;
grant execute on function public.is_spot_editable(bigint) to anon, authenticated;
grant execute on function public.is_spot_folder_editable(text) to anon, authenticated;

-- ---------------------------------------------------------
-- 3. 以前の「RECメンバーだけ編集できる」ルールを外す
--    外す前に、元のルールを map_backup スキーマに保存しておく
--    （戻すときは 2026-10-13_rollback.sql を実行）
-- ---------------------------------------------------------
create schema if not exists map_backup;
revoke all on schema map_backup from anon, authenticated;

create table if not exists map_backup.policies_20261013 (
    schemaname name,
    tablename name,
    policyname name,
    permissive text,
    roles name[],
    cmd text,
    qual text,
    with_check text,
    saved_at timestamptz not null default now()
);

create table if not exists map_backup.backup_done_20261013 (
    id int primary key
);

-- 最初の実行時だけ保存する（2回目以降に新しいルールで上書きしないため）
insert into map_backup.policies_20261013
    (schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check)
select schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check
from pg_policies
where not exists (select 1 from map_backup.backup_done_20261013)
  and (
        (schemaname = 'public' and tablename in ('spots', 'spot_images'))
        or (
            schemaname = 'storage'
            and tablename = 'objects'
            and (coalesce(qual, '') || coalesce(with_check, '')) like '%spot-images%'
        )
  );

insert into map_backup.backup_done_20261013 (id)
values (1)
on conflict (id) do nothing;

do $$
declare
    p record;
begin
    for p in
        select policyname, tablename
        from pg_policies
        where schemaname = 'public'
          and tablename in ('maps', 'spots', 'spot_images')
    loop
        execute format('drop policy %I on public.%I', p.policyname, p.tablename);
    end loop;

    for p in
        select policyname
        from pg_policies
        where schemaname = 'storage'
          and tablename = 'objects'
          and (coalesce(qual, '') || coalesce(with_check, '')) like '%spot-images%'
    loop
        execute format('drop policy %I on storage.objects', p.policyname);
    end loop;
end $$;

alter table public.maps enable row level security;
alter table public.spots enable row level security;
alter table public.spot_images enable row level security;

-- ---------------------------------------------------------
-- 4. 新しいルール
-- ---------------------------------------------------------

-- maps：誰でも見られる／作成・変更・削除は管理者だけ
create policy "maps: 誰でも閲覧"
    on public.maps for select
    to anon, authenticated
    using (true);

create policy "maps: 管理者が作成"
    on public.maps for insert
    to authenticated
    with check (public.is_map_admin());

create policy "maps: 管理者が変更"
    on public.maps for update
    to authenticated
    using (public.is_map_admin())
    with check (public.is_map_admin());

create policy "maps: 管理者が削除"
    on public.maps for delete
    to authenticated
    using (public.is_map_admin());

-- spots：誰でも見られる／ロック解除中のマップなら誰でも追加・編集／削除は管理者だけ
create policy "spots: 誰でも閲覧"
    on public.spots for select
    to anon, authenticated
    using (true);

create policy "spots: ロック解除中なら追加"
    on public.spots for insert
    to anon, authenticated
    with check (public.is_map_unlocked(map_id) or public.is_map_admin());

create policy "spots: ロック解除中なら編集"
    on public.spots for update
    to anon, authenticated
    using (public.is_map_unlocked(map_id) or public.is_map_admin())
    with check (public.is_map_unlocked(map_id) or public.is_map_admin());

create policy "spots: 管理者が削除"
    on public.spots for delete
    to authenticated
    using (public.is_map_admin());

-- spot_images：誰でも見られる／ロック解除中のマップなら誰でも追加・削除
create policy "spot_images: 誰でも閲覧"
    on public.spot_images for select
    to anon, authenticated
    using (true);

create policy "spot_images: ロック解除中なら追加"
    on public.spot_images for insert
    to anon, authenticated
    with check (public.is_spot_editable(spot_id) or public.is_map_admin());

create policy "spot_images: ロック解除中なら削除"
    on public.spot_images for delete
    to anon, authenticated
    using (public.is_spot_editable(spot_id) or public.is_map_admin());

-- Storage（spot-images バケット）：写真ファイルも同じルール
create policy "spot-images: 誰でも閲覧"
    on storage.objects for select
    to anon, authenticated
    using (bucket_id = 'spot-images');

create policy "spot-images: ロック解除中なら追加"
    on storage.objects for insert
    to anon, authenticated
    with check (
        bucket_id = 'spot-images'
        and (
            public.is_spot_folder_editable((storage.foldername(name))[1])
            or public.is_map_admin()
        )
    );

create policy "spot-images: ロック解除中なら削除"
    on storage.objects for delete
    to anon, authenticated
    using (
        bucket_id = 'spot-images'
        and (
            public.is_spot_folder_editable((storage.foldername(name))[1])
            or public.is_map_admin()
        )
    );

commit;
